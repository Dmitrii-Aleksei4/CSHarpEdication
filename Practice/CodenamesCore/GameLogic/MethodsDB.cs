        public string GetRulesGame()
        {
            string info = """
                
                Добрый день, дорогой друг!
                В игре есть несколько важных моментов, которые нужно помнить, и правил, которые следует выполнять.

                ПОМНИМ:
                В игре, в зависимости от поля, есть 4 вида цветных карт (агентов), которые скрыты под словами:

                Красные — это команда «Красных»;

                Синие — это команда «Синих»;

                Чёрные (в некоторых версиях — бирюзовые) — это убийца;

                Серые (бежевые) — это мирные жители.

                Процесс игры:
                Капитаны видят специальное поле для капитанов (могут сфотографировать его на телефон). Участники видят только 
                поле для участников и не видят раскладку капитана.

                У капитана есть время, чтобы придумать ассоциацию из одного слова с агентами (словами) своего цвета. После этого 
                он сообщает свою ассоциацию команде и называет цифру — сколько, по его предположению, агентов (слов) связано с этой 
                ассоциацией.

                Команда по этой ассоциации обсуждает версии и выбирает (вводит) предполагаемые слова (агентов). Карты открываются
                по очереди, в любом порядке. Если открыли слово своего цвета — игра продолжается до истечения отведённого времени 
                либо до исчерпания количества ассоциируемых слов, заданных капитаном.

                Выигрывает та команда, у которой счетчике агентов не осталось больше слов для отгадывания, ИЛИ команда соперников 
                открыла чёрное (бирюзовое) слово (т.е. проиграла).

                ПРАВИЛА:

                Ассоциации не могут быть однокоренными, содержать цифры или одну букву, а также иным способом прямо наводить на 
                ответ (кроме самой ассоциации).
                Пример: Нельзя: «столбец 5», «лево 3», «2К3», «Ц2».

                Нельзя ассоциировать больше слов, чем у вашей команды осталось неразгаданных на поле.
                Пример: Осталось отгадать 3 слова, а капитан загадал 4.

                При открытии чёрного (бирюзового) слова (агента) команда, открывшая его, автоматически проигрывает.

                При открытии слова противоположной команды ход переходит к этой противоположной команде.

                За один ход, в течение обговорённого времени, нельзя открыть больше слов, чем озвучил капитан.

                При открытии мирного жителя (серый/бежевый) ход остаётся за командой, открывающей слова, но цифра озвученных 
                капитаном ассоциируемых слов уменьшается на 1.

                При открытии своего цвета цифра озвученных капитаном ассоциируемых слов также уменьшается на 1.

                Первым ходит та команда (капитан), у которой на поле изначально больше агентов (карт своего цвета).

                ЗНАЧЕНИЯ ТАЙМЕРА ПО УМОЛЧАНИЮ:

                Таймер на раздумья для первого хода первого капитана — 2 минуты.

                Таймер на последующие раздумья обоих капитанов — 1 минута.

                Таймер для команды на обсуждение версий и открытие слов — 1 минута.

                """;
            
            return info;
        }
