namespace Library_3
{
    public class MathHelper
    {
        public int  Sum (int i, int y)
        {
            return i+y;
        }
        public int Difference(int i, int y)
        {
            return i-y;
        }

        public int Сomposition(int i, int y)
        {
            return i*y;
        }
        public int Remains (int i, int y)
        {
            return i/y;
        }
    }
}
